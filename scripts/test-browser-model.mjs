import assert from 'node:assert/strict'
import {appendKeys,appendRedisValues,redisContentCommand,quoteIdentifier,prettyValue} from '../web/src/workbench/browserModel.js'
assert.deepEqual(appendKeys(['a'],['a','b','b']),{keys:['a','b'],capped:false})
const many=appendKeys([],Array.from({length:1100},(_,i)=>String(i)))
assert.equal(many.keys.length,1000);assert.equal(many.capped,true)
const longKeys=appendKeys([],Array.from({length:50},(_,i)=>String(i)+'x'.repeat(65536)))
assert(longKeys.keys.length<50);assert(longKeys.capped)
assert(longKeys.keys.reduce((n,k)=>n+new TextEncoder().encode(JSON.stringify(k)).length,0)<=2*1024*1024)
assert.deepEqual(appendRedisValues('hash',['a','old','b','second'],['a','new','c','third']),{values:['a','new','b','second','c','third'],capped:false})
assert.deepEqual(appendRedisValues('set',['a','b'],['b','c']),{values:['a','b','c'],capped:false})
assert.deepEqual(appendRedisValues('list',['same'],['same']),{values:['same','same'],capped:false})
const longValues=appendRedisValues('hash',[],Array.from({length:50},(_,i)=>['field'+i,'v'.repeat(65536)]).flat())
assert(longValues.values.length<100);assert(longValues.capped)
const largeSet=appendRedisValues('set',[],Array.from({length:1000},(_,i)=>String(i)))
assert.equal(largeSet.values.length,1000);assert(largeSet.capped)
assert.equal(redisContentCommand('menu:space key','list','0',50),'LRANGE "menu:space key" 50 99')
assert.equal(redisContentCommand('menu:z','zset','42'),'ZSCAN "menu:z" 42 COUNT 50')
assert.equal(redisContentCommand('menu:stream','stream'),'')
assert.equal(quoteIdentifier('MixedCase'),'`MixedCase`')
assert.throws(()=>quoteIdentifier('menu; DROP TABLE menu'))
assert.equal(prettyValue('1234567890123456789'),'1234567890123456789')
const deep='['.repeat(1000)+'0'+']'.repeat(1000)
assert.equal(prettyValue(deep),deep,'deep JSON expanded into unbounded indentation')
assert.equal(prettyValue('{"id":1234567890123456789,"value":1.1234567890123456789,"empty":[],"message":"a\\\"b"}'),'{\n  "id": 1234567890123456789,\n  "value": 1.1234567890123456789,\n  "empty": [],\n  "message": "a\\\"b"\n}')
console.log(JSON.stringify({ok:true,checks:['deduplication','item and byte limits','field replacement','list duplicates preserved','bounded typed commands','identifier injection refusal','JSON formatting preserves numeric precision']}))
