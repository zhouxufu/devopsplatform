// Run only against an EMPTY, disposable standalone preview (not the gateway).
// PLAYWRIGHT_MODULE may point to an existing local Playwright index.mjs.
import assert from 'node:assert/strict'
const base = process.env.DELIVERY_UI_TEST_URL || 'http://127.0.0.1:19813'
const url = new URL(base)
assert.equal(url.hostname, '127.0.0.1', 'UI regression is local-only')
assert(!['9800','19803'].includes(url.port), 'Do not test against normal platform ports')
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {}), headless:true })
const page = await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[]
page.on('pageerror', error=>errors.push(error.message))
page.on('dialog', dialog=>dialog.accept())
const request = page.request
const read = async path => {const response=await request.get(base+path);assert(response.ok(),path);return response.json()}
try {
  const setup=await read('/api/setup')
  const services=await read('/api/services')
  assert.equal(services.length,0,'Use an empty disposable preview, not an application database')
  assert(setup.environments.every(e=>e.name==='qa-ui'),'Refusing non-QA environments')
  for (const path of ['/api/work-items','/api/changes','/api/release-versions']) {
    assert((await read(path)).every(v=>v.title.startsWith('UI回归')),`Refusing non-QA data in ${path}`)
  }
  assert((await read('/api/delivery/templates')).every(v=>v.name.startsWith('UI回归')),'Refusing non-QA templates')
  if(!setup.completed){const response=await request.post(base+'/api/setup/environments',{data:{environments:[{name:'qa-ui',display_name:'UI 回归环境'}]}});assert(response.ok(),await response.text())}
  // Standalone preview intentionally has no platform auth endpoint.
  await page.route('**/api/me',route=>route.fulfill({json:{username:'local',role:'admin'}}))
  const suffix=Date.now().toString(36)
  const title='UI回归需求-'+suffix, change='UI回归变更-'+suffix, version='UI回归版本-'+suffix, tpl='UI回归编排-'+suffix
  const dialog=()=>page.getByRole('dialog')
  const field=(name)=>dialog().locator('label').filter({hasText:new RegExp('^'+name)}).locator('input,textarea').first()
  const select=async(label,option)=>{await dialog().locator('label').filter({hasText:new RegExp('^'+label)}).locator('.el-select').click();await page.getByRole('option',{name:option,exact:true}).click()}
  const waitFor=async name=>{await page.getByText(name,{exact:true}).first().waitFor()}
  await page.goto(base+'/ui#/changes?tab=work')
  await page.getByRole('button',{name:'＋ 新建需求 / 关联 BUG'}).click()
  await field('标题').fill(title)
  await dialog().getByRole('button',{name:'保存',exact:true}).click()
  await waitFor(title)
  // Cancel must work even with empty required fields.
  await page.getByRole('button',{name:'＋ 新建需求 / 关联 BUG'}).click()
  await dialog().getByRole('button',{name:'取消',exact:true}).click()
  await dialog().waitFor({state:'hidden'})
  await page.getByRole('button',{name:'独立变更',exact:true}).click()
  await page.getByRole('button',{name:'＋ 新建变更'}).click()
  await field('标题').fill(change)
  await select('变更类型','人工操作')
  await field('实施内容').fill('核对本次发布的业务验收结果')
  const wi=(await read('/api/work-items')).find(w=>w.title===title)
  await select('关联需求 / BUG',`#${wi.id} ${title}`)
  await dialog().getByRole('button',{name:'保存',exact:true}).click()
  await page.locator('.record').filter({hasText:change}).getByRole('button',{name:'标记就绪'}).click()
  await page.locator('.record').filter({hasText:change}).getByText('已就绪',{exact:true}).waitFor()
  await page.getByRole('button',{name:'发布版本',exact:true}).click()
  await page.getByRole('button',{name:'＋ 创建发布版本'}).click()
  await field('标题').fill(version)
  await field('版本号').fill('qa-'+suffix)
  await select('按需求 / BUG',title)
  await dialog().locator('.selection').getByText(change,{exact:false}).waitFor()
  await dialog().getByRole('button',{name:'保存',exact:true}).click()
  await page.locator('.record').filter({hasText:version}).getByRole('button',{name:'标记就绪'}).click()
  await page.locator('.record').filter({hasText:version}).getByText('已就绪',{exact:true}).waitFor()
  await page.getByRole('link',{name:'🚀 编排'}).click()
  await page.getByRole('button',{name:'＋ 新建编排'}).click()
  await field('名称').fill(tpl)
  await select('交付范围','由发布版本推导')
  await dialog().locator('.node .el-select').first().click()
  await page.getByRole('option',{name:'人工确认',exact:true}).click()
  await dialog().locator('.node-head input').first().fill('人工验收')
  await field('操作 / 确认说明').fill('确认版本验收通过')
  await dialog().getByRole('button',{name:'保存模板'}).click()
  await page.locator('article.card').filter({hasText:tpl}).getByRole('button',{name:'发起交付'}).click()
  await select('发布版本','qa-'+suffix+' · '+version)
  await dialog().getByRole('button',{name:'检查范围与配置'}).click()
  await dialog().getByText('✓ 校验通过。提交后冻结制品、目标和节点；修改需另建执行单。').waitFor()
  await dialog().getByRole('button',{name:'提交执行单（不立即部署）'}).click()
  await dialog().getByRole('button',{name:'确认人工节点'}).click()
  await dialog().getByRole('button',{name:'确认编排完成'}).click()
  const saved=(await read('/api/delivery/runs')).find(r=>r.plan.template.name===tpl)
  assert.equal(saved.status,'success')
  assert.equal(saved.plan.services.length,0,'Manual-only version deployed an unrelated app')
  assert.equal((await read('/api/releases')).length,0,'UI regression unexpectedly created a deployment')
  await dialog().locator('.el-dialog__headerbtn').click()
  await page.getByRole('link',{name:'🧾 变更'}).click()
  await page.getByRole('button',{name:'发布版本',exact:true}).click()
  await page.locator('.record').filter({hasText:version}).getByRole('button',{name:`UI 回归环境 · #${saved.id} · 成功`}).click()
  await dialog().getByText(tpl,{exact:true}).waitFor()
  await page.reload()
  await dialog().getByText(tpl,{exact:true}).waitFor()
  await page.screenshot({path:process.env.DELIVERY_UI_SCREENSHOT||'runtime/delivery-ui-test.png',fullPage:true})
  await page.setViewportSize({width:900,height:800})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Horizontal page overflow')
  assert.deepEqual(errors,[],'Browser runtime errors')
  console.log(JSON.stringify({ok:true,checks:['create demand','cancel empty required form','independent change','demand → version scope','version-driven orchestration','preview','manual execution','no unintended deployment','version → execution trace','persist after refresh','browser errors','900px layout'],run_id:saved.id}))
} finally {await browser.close()}
