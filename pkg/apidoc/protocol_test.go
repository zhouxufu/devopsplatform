func TestMaintainerMetadataPrecedenceAndImmutableSource(t *testing.T) {
	for _, tc := range []struct{ operation, contact, want string }{
		{`"x-maintainer":" 李四 "`, `{"name":"张三"}`, "李四"},
		{`"x-maintainer":" "`, `{"name":" 张三 "}`, "张三"},
		{`"x-maintainer":12`, `{"name":"张三"}`, "张三"},
		{`"x-maintainer":"bad\nvalue"`, `{"email":"mail@example.invalid"}`, ""},
		{`"x-maintainer":null`, `null`, ""},
	} {
		raw := []byte(`{"openapi":"3.0.3","info":{"title":"接口","version":"1","contact":` + tc.contact + `},"paths":{"/x":{"get":{` + tc.operation + `,"operationId":"same-id","responses":{"200":{"description":"成功"}}}}}}`)
		_, ops, digest, err := Parse(raw)
		if err != nil || len(ops) != 1 || ops[0].Maintainer != tc.want {
			t.Fatalf("%+v %v", ops, err)
		}
		var original map[string]json.RawMessage
		if json.Unmarshal(ops[0].Definition, &original) != nil || string(original["operationId"]) != `"same-id"` {
			t.Fatal("source identity changed")
		}
		_, _, again, _ := Parse(raw)
		if digest != again {
			t.Fatal("reading maintainer mutated source")
		}
	}
}

const specimen = `{"openapi": "3.0.3", "info": {"title": "订单接口", "version": "v1"}, "paths": {"/orders": {"post": {"summary": "创建订单", "responses": {"201": {"description": "created"}}}}, "/events": {"get": {"responses": {"200": {"description": "stream", "content": {"text/event-stream": {"schema": {"type": "string"}}}}}}}}}`

func TestDocumentParsingStreamingAndDigest(t *testing.T) {
	d, ops, sum, err := Parse([]byte(specimen))
	if err != nil || d.Info.Title != "订单接口" || len(ops) != 2 {
		t.Fatalf("%+v %v", d, err)
	}
	streams := 0
	for _, o := range ops {
		if o.SSE {
			streams++
			if o.Path != "/events" {
				t.Fatal(o)
			}
		}
	}
	if streams != 1 {
		t.Fatal(ops)
	}
	_, _, same, err := Parse([]byte(" \n" + specimen))
	if err != nil || sum != same {
		t.Fatal("nonsemantic whitespace changed identity")
	}
	for _, bad := range []string{`{}`, strings.Replace(specimen, `"3.0.3"`, `"2.0"`, 1), strings.Replace(specimen, `"/orders"`, `"orders"`, 1), strings.Repeat(" ", MaxDocument+1)} {
		if _, _, _, err := Parse([]byte(bad)); err == nil {
			t.Fatal("accepted invalid document")
		}
	}
}
func TestGeneratedPathsAndPlans(t *testing.T) {
	good := Plan{Version: 1, Provider: "provider", ProviderVersion: "1", Tool: "maven", Tasks: []string{"docs:openapi"}, InputFiles: []string{"src/docs.json"}, OutputFile: "target/docs/openapi.json", Format: "openapi-json"}
	if err := ValidatePlan(good); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{"/etc/passwd", "../openapi.json", "target/../../openapi.json", "target\\doc.json", "target/a\n.json", "src/openapi.json"} {
		v := good
		v.OutputFile = path
		if ValidatePlan(v) == nil {
			t.Fatal(path)
		}
	}
	for _, task := range []string{"-Dfoo=bar", "docs;touch /tmp/oops", "docs:openapi && curl x"} {
		v := good
		v.Tasks = []string{task}
		if ValidatePlan(v) == nil {
			t.Fatal(task)
		}
	}
}

// Generated by smart-doc Maven 2.4.6 from the synthetic Java fixture.
// That version exports */* even for produces=text/event-stream; do not guess SSE.
func TestRealSmartDocOutput(t *testing.T) {
	raw, err := os.ReadFile("testdata/smart-doc-2.4.6.json")
	if err != nil {
		t.Fatal(err)
	}
	d, ops, digest, err := Parse(raw)
	if err != nil || d.Info.Version != "1.0.0" || len(ops) != 2 || !strings.HasPrefix(digest, "sha256:") {
		t.Fatalf("%+v %v", d, err)
	}
	for _, op := range ops {
		if op.SSE {
			t.Fatal("old generator did not preserve event-stream content type", op)
		}
	}
}

// Captured from the controlled Java fixture using Gradle 8 / JDK 17 and
// smart-doc Gradle plugin 4.0.0, changing Order.amount from Integer to String.
func TestRealGradleSmartDocOutputAndFieldChanges(t *testing.T) {
	before, err := os.ReadFile("testdata/smart-doc-gradle-4.0.0-before.json")
	if err != nil {
		t.Fatal(err)
	}
	after, err := os.ReadFile("testdata/smart-doc-gradle-4.0.0-after.json")
	if err != nil {
		t.Fatal(err)
	}
	if _, ops, _, err := Parse(before); err != nil || len(ops) == 0 {
		t.Fatal(ops, err)
	}
	diff, err := Compare(before, after)
	if err != nil || diff.Summary.Modified == 0 {
		t.Fatal(diff, err)
	}
	found := false
	for _, change := range diff.Changes {
		for _, field := range change.Fields {
			// smart-doc hashes schema names; a type change may replace the
			// referenced object instead of retaining the same component path.
			if strings.Contains(field.Path, "/amount/type") || (strings.Contains(field.Before+field.After, `"amount"`) && strings.Contains(field.Before+field.After, `"type"`)) {
				found = true
			}
		}
	}
	if !found {
		t.Fatalf("real schema type change missing: %+v", diff)
	}
}

func TestDocumentDigestPreservesLargeExampleNumbers(t *testing.T) {
	a := strings.Replace(specimen, `"title": "订单接口"`, `"title": "订单接口", "x-example": 9007199254740992`, 1)
	b := strings.Replace(a, "9007199254740992", "9007199254740993", 1)
	_, _, first, err := Parse([]byte(a))
	if err != nil {
		t.Fatal(err)
	}
	_, _, second, err := Parse([]byte(b))
	if err != nil || first == second {
		t.Fatal("distinct large example values must have distinct digests", err)
	}
}
