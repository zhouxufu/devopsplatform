func TestAPIDocumentEnvironmentSourcesAndFrozenSelection(t *testing.T) {
	st, h := apiTestingFixture(t)
	documentBrokerFixture(t)
	for _, e := range []Environment{{Name: "sandbox", DisplayName: "开发沙箱", Purpose: "development"}, {Name: "qa2", DisplayName: "回归测试", Purpose: "test"}} {
		if err := st.UpsertEnvironment(e); err != nil {
			t.Fatal(err)
		}
	}
	sv := st.GetService("orders")
	sv.BuildTool = "maven"
	legacy := apidoc.Source{Provider: "smart-doc", Settings: json.RawMessage(`{"plugin_version":"2.7.3","config_file":"smart-doc.json"}`)}
	if e := st.saveAPIDocumentSource(sv, legacy, "fixture"); e != nil {
		t.Fatal(e)
	}
	for _, env := range []string{"sandbox", "qa2", "prod"} {
		v, inherited, e := st.environmentDocumentSource(sv, env)
		if e != nil || !inherited || v.Revision != 0 || v.OnBuild != (env != "prod") {
			t.Fatal(env, v, e)
		}
	}
	source, _, _ := st.environmentDocumentSource(sv, "qa2")
	source.Settings = json.RawMessage(`{"plugin_version":"2.7.3","config_file":"qa-smart-doc.json"}`)
	if e := st.saveEnvironmentDocumentSource(sv, "qa2", source, "fixture"); e != nil {
		t.Fatal(e)
	}
	if st.saveEnvironmentDocumentSource(sv, "qa2", source, "fixture") == nil {
		t.Fatal("stale environment config accepted")
	}
	if e := st.freezeAPIDocumentation(sv, false, "qa2"); e != nil || sv.APIDocumentation == nil || sv.APIDocumentation.Environment != "qa2" || sv.APIDocumentation.Plan.InputFiles[0] != "qa-smart-doc.json" {
		t.Fatal(sv.APIDocumentation, e)
	}
	source, _, _ = st.environmentDocumentSource(sv, "qa2")
	source.OnBuild = false
	if e := st.saveEnvironmentDocumentSource(sv, "qa2", source, "fixture"); e != nil {
		t.Fatal(e)
	}
	if e := st.freezeAPIDocumentation(sv, true); e != nil || !sv.APIDocumentation.Source.OnBuild {
		t.Fatal("replay used changed source", e)
	}
	if e := st.freezeAPIDocumentation(sv, false, "prod"); e != nil || sv.APIDocumentation != nil {
		t.Fatal("production generated by default", e)
	}
	// Source revisions are independent, and non-admin readers do not see plugin settings.
	w := apiTestingRequest(h, "GET", "/api/api-documents/source?service=orders&environment=qa2", "alice", "member", nil)
	if w.Code != 200 || strings.Contains(w.Body.String(), "qa-smart-doc") {
		t.Fatal(w.Body.String())
	}
	w = apiTestingRequest(h, "GET", "/api/api-documents/source?service=orders&environment=missing", "alice", "member", nil)
	if w.Code != 400 {
		t.Fatal(w.Code)
	}
}
func TestAPIDocumentVersionsScopeAndFrozenComparisonBaseline(t *testing.T) {
	st, h := apiTestingFixture(t)
	sv := st.GetService("orders")
	first, e := st.recordAPIDocument(sv, APIDocumentSnapshot{Environment: "test", RunID: 1, ArtifactID: 1}, []byte(apiDocumentFixture))
	if e != nil {
		t.Fatal(e)
	}
	changed := strings.Replace(apiDocumentFixture, `"description":"ok"`, `"description":"updated"`, 1)
	production, e := st.recordAPIDocument(sv, APIDocumentSnapshot{Environment: "prod", RunID: 1, ArtifactID: 1}, []byte(changed))
	if e != nil {
		t.Fatal("same artifact cannot have separate environmental docs", e)
	}
	second, e := st.recordAPIDocument(sv, APIDocumentSnapshot{Environment: "test", RunID: 2, ArtifactID: 2}, []byte(changed))
	if e != nil {
		t.Fatal(e)
	}
	v, _ := st.apiDocumentSnapshot(sv.ApplicationID, second)
	if v.BaselineID != first || v.Changes.Modified != 1 {
		t.Fatal(v)
	}
	same, e := st.recordAPIDocument(sv, APIDocumentSnapshot{Environment: "test", RunID: 2, ArtifactID: 2}, []byte(changed))
	if e != nil || same != second {
		t.Fatal("duplicate snapshot", same, e)
	}
	third, e := st.recordAPIDocument(sv, APIDocumentSnapshot{Environment: "test", RunID: 3, ArtifactID: 3}, []byte(changed))
	if e != nil {
		t.Fatal(e)
	}
	v, _ = st.apiDocumentSnapshot(sv.ApplicationID, third)
	if v.BaselineID != second || v.Changes.Unchanged != 1 {
		t.Fatal(v)
	}
	for _, path := range []string{fmt.Sprintf("/api/api-documents/%d/comparison?service=orders&base_id=%d", second, production), fmt.Sprintf("/api/api-documents/%d/comparison?service=other", second), fmt.Sprintf("/api/api-documents/%d?service=orders&environment=prod", second)} {
		w := apiTestingRequest(h, "GET", path, "alice", "member", nil)
		if w.Code == 200 {
			t.Fatal("cross-scope accepted", path, w.Body.String())
		}
	}
	w := apiTestingRequest(h, "GET", fmt.Sprintf("/api/api-documents/%d/comparison?service=orders", second), "alice", "member", nil)
	if w.Code != 200 || !strings.Contains(w.Body.String(), `"modified":1`) {
		t.Fatal(w.Body.String())
	}
	w = apiTestingRequest(h, "GET", "/api/api-documents?service=orders&environment=prod", "alice", "member", nil)
	var list []APIDocumentSnapshot
	json.Unmarshal(w.Body.Bytes(), &list)
	if len(list) != 1 || list[0].ID != production || list[0].BaselineID != 0 {
		t.Fatal(w.Body.String())
	}
	v, _ = st.apiDocumentSnapshot(sv.ApplicationID, second)
	if v.BaselineID != first {
		t.Fatal("later build changed older baseline")
	}
}

// Entirely local synthetic package and document command; no real app build/deploy.
func documentPipelineFixture(t *testing.T, st *Store) (*PipelineRunner, *Service) {
	t.Helper()
	root := t.TempDir()
	workspace := filepath.Join(root, "source")
	os.MkdirAll(workspace, 0700)
	for name, body := range map[string]string{"pom.xml": "<project/>", "smart-doc.json": "{}", "fixture-openapi.json": apiDocumentFixture, "mvnw": "#!/bin/sh\nset -eu\nmkdir -p target/api-docs\ncp fixture-openapi.json target/api-docs/openapi.json\n"} {
		if e := os.WriteFile(filepath.Join(workspace, name), []byte(body), 0700); e != nil {
			t.Fatal(e)
		}
	}
	libroot := filepath.Join(root, "steps", "fixture-package")
	os.MkdirAll(libroot, 0700)
	os.WriteFile(filepath.Join(libroot, "step.yaml"), []byte("id: fixture-package\nname: 合成制品\nkind: package\ncategory: 打包\nproduces: jar\n"), 0600)
	os.WriteFile(filepath.Join(libroot, "run.sh"), []byte("set -eu\nprintf fixture-jar > \"$LP_OUTPUT_DIR/result.jar\"\nprintf 'ARTIFACT=%s\\nARTIFACT_KIND=jar\\n' \"$LP_OUTPUT_DIR/result.jar\" > \"$LP_OUTPUTS_FILE\"\n"), 0700)
	if e := st.UpsertService(Service{Name: "orders", ArtifactType: "jar", BuildTool: "maven", Workdir: workspace, MavenExecutable: "auto", MavenGoals: "package", Steps: []StepInst{{Step: "fixture-package"}}}); e != nil {
		t.Fatal(e)
	}
	hub := NewLogHub()
	pr := NewPipelineRunner(st, NewBuilder(st, root, hub), hub, nil, NewStepLib(filepath.Dir(libroot)))
	return pr, st.GetService("orders")
}
func executeDocumentFixture(t *testing.T, pr *PipelineRunner, sv *Service, env string, raw string, required bool) *PipelineRun {
	t.Helper()
	os.WriteFile(filepath.Join(sv.Workdir, "fixture-openapi.json"), []byte(raw), 0600)
	v := *sv
	v.DocumentEnvironment = env
	v.APIDocumentation = &apidoc.Frozen{Environment: env, Source: apidoc.Source{Provider: "smart-doc", OnBuild: true, Required: required}, Plan: &apidoc.Plan{Version: 1, Provider: "smart-doc", ProviderVersion: "1.0.0", Tool: "maven", Tasks: []string{"docs:openapi"}, InputFiles: []string{"smart-doc.json"}, OutputFile: "target/api-docs/openapi.json", Format: "openapi-json"}}
	run := &PipelineRun{Service: v.Name, Actor: "fixture-admin", StartedAt: time.Now().Unix(), Stages: pr.plannedStages(&v)}
	if e := pr.st.CreateRun(run); e != nil {
		t.Fatal(e)
	}
	if e := pr.st.saveBuildSnapshot(run.ID, &v, pr.st.GetServiceDelivery(v.Name)); e != nil {
		t.Fatal(e)
	}
	pr.runContext(context.Background(), run.ID, &v, false)
	return pr.st.GetRun(run.ID)
}
func TestAPIDocumentPipelineShowsGenerationStageAndDoesNotHideFailure(t *testing.T) {
	st, _ := apiTestingFixture(t)
	pr, sv := documentPipelineFixture(t, st)
	run := executeDocumentFixture(t, pr, sv, "test", apiDocumentFixture, true)
	if run.Status != "success" || len(run.Stages) != 2 || run.Stages[1].Status != "success" || !strings.Contains(run.Stages[1].Name, "smart-doc") || !strings.Contains(pr.st.RunLog(run.ID), "文档对比：新增 1") {
		t.Fatalf("%+v\n%s", run, pr.st.RunLog(run.ID))
	}
	second := executeDocumentFixture(t, pr, sv, "test", strings.Replace(apiDocumentFixture, "ok", "changed", 1), true)
	if second.Status != "success" || !strings.Contains(pr.st.RunLog(second.ID), "修改 1") {
		t.Fatal(pr.st.RunLog(second.ID))
	}
	os.Remove(filepath.Join(sv.Workdir, "smart-doc.json"))
	failed := executeDocumentFixture(t, pr, sv, "test", apiDocumentFixture, true)
	if failed.Status != "failed" || failed.Stages[1].Status != "failed" {
		t.Fatal(failed)
	}
	warning := executeDocumentFixture(t, pr, sv, "test", apiDocumentFixture, false)
	if warning.Status != "success" || warning.Stages[1].Status != "warning" {
		t.Fatal(warning)
	}
	// Reports and source configuration reads must never start another build.
}

func TestAPIDocumentAutomaticBuildRequiresAndFreezesSelectedEnvironment(t *testing.T) {
	st, _ := apiTestingFixture(t)
	documentBrokerFixture(t)
	pr, sv := documentPipelineFixture(t, st)
	source := apidoc.Source{Provider: "smart-doc", OnBuild: true, Required: true, Settings: json.RawMessage(`{"plugin_version":"2.7.3","config_file":"smart-doc.json"}`)}
	if e := st.saveEnvironmentDocumentSource(sv, "test", source, "fixture"); e != nil {
		t.Fatal(e)
	}
	if _, e := pr.StartWithOptions(sv, false, PipelineRunOptions{}, "fixture"); e == nil || !strings.Contains(e.Error(), "选择") {
		t.Fatal("unscoped build started", e)
	}
	if len(st.Runs(sv.Name, 10)) != 0 {
		t.Fatal("validation started a build")
	}
	id, e := pr.StartWithOptions(sv, false, PipelineRunOptions{BuildEnvironment: "test"}, "fixture")
	if e != nil {
		t.Fatal(e)
	}
	var run *PipelineRun
	for until := time.Now().Add(8 * time.Second); time.Now().Before(until); {
		run = st.GetRun(id)
		if run.Status != "running" {
			break
		}
		time.Sleep(10 * time.Millisecond)
	}
	if run == nil || run.Status != "success" || len(run.Stages) != 2 || run.Stages[1].Status != "success" {
		t.Fatalf("%+v\n%s", run, st.RunLog(id))
	}
	env, frozen, e := st.buildDocumentContext(id)
	if e != nil || env != "test" || frozen.Environment != "test" {
		t.Fatal(env, frozen, e)
	}
	var count int
	st.db.QueryRow(`SELECT COUNT(*) FROM api_document_versions WHERE run_id=? AND environment='test'`, id).Scan(&count)
	if count != 1 {
		t.Fatal("environment not stored", count)
	}
}
