func TestAPIDocumentLegacySnapshotsMigrateWithoutGuessingEnvironment(t *testing.T) {
	dir := t.TempDir()
	st, e := Open(dir)
	if e != nil {
		t.Fatal(e)
	}
	if e = st.UpsertService(Service{Name: "orders", ArtifactType: "jar"}); e != nil {
		t.Fatal(e)
	}
	sv := st.GetService("orders")
	_, _, digest, _ := apidoc.Parse([]byte(apiDocumentFixture))
	for _, id := range []int{91, 95} {
		_, e = st.db.Exec(`INSERT INTO api_document_snapshots(id,application_id,service,run_id,artifact_id,artifact_digest,commit_ref,provider,provider_version,digest,document,created_at) VALUES(?,?,?,0,?,'','','import','',?,?,1)`, id, sv.ApplicationID, sv.Name, id, digest, apiDocumentFixture)
		if e != nil {
			t.Fatal(e)
		}
	}
	st.Close()
	st, e = Open(dir)
	if e != nil {
		t.Fatal(e)
	}
	defer st.Close()
	v, e := st.apiDocumentSnapshot(sv.ApplicationID, 95)
	if e != nil || v.Environment != "" || v.BaselineID != 91 || v.Digest != digest || v.Compared {
		t.Fatal(v, e)
	}
	id, e := st.recordAPIDocument(sv, APIDocumentSnapshot{RunID: 96}, []byte(apiDocumentFixture))
	if e != nil || id <= 95 {
		t.Fatal("immutable IDs overwritten", id, e)
	}
}
